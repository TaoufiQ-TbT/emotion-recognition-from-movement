@app.server.route("/media/<job_id>/<path:filename>")
def serve_media(job_id: str, filename: str):
    """Serve an analyzed video to the player."""
    job = job_store.get(job_id)
    if job is None:
        abort(404)
    # send_from_directory rejects any filename that would leave the job's upload folder.
    return send_from_directory(job.video_path.parent, filename)


@app.server.route("/poses/<job_id>")
def serve_poses(job_id: str):
    """2D landmarks of an analysis, compact, for the skeleton overlay: [time, [x, y, visibility] * 33]."""
    job = job_store.get(job_id)
    pose_file = job.run_dir / "poses.json" if job else None
    if pose_file is None or not pose_file.exists():
        abort(404)
    frames = []
    for frame in json.loads(pose_file.read_text()).get("frames", []):
        landmarks = sorted(frame.get("landmarks_image") or [], key=lambda lm: lm["index"])
        if len(landmarks) == 33:
            values = [round(v, 4) for lm in landmarks for v in (lm["x"], lm["y"], lm.get("visibility", 1.0))]
            frames.append([round(frame["timestamp_s"], 3), values])
    return jsonify({"frames": frames})


@app.server.route("/upload_chunk", methods=["POST"])
def upload_chunk():
    """Receive a file chunk and append it to a temp file."""
    chunk_file = upload_file_for(request.headers.get("X-Upload-ID"))
    if chunk_file is None:
        return "Invalid Upload ID", 400

    chunk_file.parent.mkdir(parents=True, exist_ok=True)

    with open(chunk_file, "ab") as f:
        f.write(request.data)

    return "OK", 200


@app.server.route("/upload_fusion", methods=["POST"])
def upload_fusion():
    """Confirm the chunked upload is complete. The browser only ever gets its ID back, never a path."""
    payload = request.get_json(silent=True) or {}
    upload_id = payload.get("upload_id")
    file_path = upload_file_for(upload_id)

    if file_path is None or not payload.get("filename"):
        return "Missing Data", 400
    if not file_path.exists():
        return "File not found", 404

    return jsonify({"upload_id": upload_id})


