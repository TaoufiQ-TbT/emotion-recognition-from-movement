# Everything that changes between the empty, processing, results and error views.
VIEW_OUTPUTS = [
    Output("app-main", "className", allow_duplicate=True),
    Output("status", "className", allow_duplicate=True),
    Output("status-text", "children", allow_duplicate=True),
    Output("progress-file", "children", allow_duplicate=True),
    Output("error-message", "children", allow_duplicate=True),
    *[Output(f"step-{key}", "className", allow_duplicate=True) for key, _ in STEPS],
    *[Output(f"step-{key}-detail", "children", allow_duplicate=True) for key, _ in STEPS],
]
STATUS = {
    "processing": ("status status-busy", "Analyzing…"),
    "ready": ("status status-ok", "Analysis complete"),
    "error": ("status status-error", "Analysis failed"),
}


def view(state: str, *, message: str = "", filename=dash.no_update, error: str = "") -> list:
    """Values for VIEW_OUTPUTS. `message` is the job message, which selects the active progress step."""
    current = next((index for prefix, index in STEP_STARTED_BY if message.startswith(prefix)), 1)
    if state != "processing":
        current = len(STEPS)
    detail = message.split("·", 1)[1].strip().capitalize() if "·" in message else ""
    classes = ["step done" if i < current else "step active" if i == current else "step" for i in range(len(STEPS))]
    details = [detail if i == current else "" for i in range(len(STEPS))]
    return [f"main state-{state}", *STATUS[state], filename, error, *classes, *details]


def no_change(count: int) -> list:
    """Tell Dash to leave `count` outputs as they are."""
    return [dash.no_update] * count


@app.callback(
    Output("frame-sampling-value", "children"),
    Output("window-value", "children"),
    Output("window-step-value", "children"),
    Output("sample-rate", "data"),
    Input("model-path", "value"),
)
def update_model_info(model_path):
    """Show the settings of the selected model in the sidebar."""
    if not is_known_checkpoint(model_path):
        return "—", "—", "—", DEFAULT_SAMPLE_RATE
    try:
        cfg = get_model_config(Path(model_path))
    except Exception:
        return "?", "?", "?", DEFAULT_SAMPLE_RATE
    # Videos must be sampled like the model's training data, not by its window stride.
    sample_rate = cfg.get("sample_rate", DEFAULT_SAMPLE_RATE)
    frames = lambda count: f"{count} frames ({count / sample_rate:.3g} s)"
    return f"{sample_rate:g} per second", frames(cfg["max_len"]), frames(cfg["window_stride"]), sample_rate


@app.callback(
    *VIEW_OUTPUTS,
    Output("status-poll", "disabled", allow_duplicate=True),
    Input("model-path", "value"),
    State("job-id", "data"),
    State("upload-trigger", "data"),
    prevent_initial_call=True,
)
def switch_model(model_path, job_id, upload_data):
    """Re-run the current video's prediction with the newly selected model."""
    if not job_id or not is_known_checkpoint(model_path) or not job_store.reprocess_job(job_id, Path(model_path)):
        return no_change(len(VIEW_OUTPUTS) + 1)
    filename = (upload_data or {}).get("filename", "")
    return [*view("processing", message="Predicting emotions", filename=filename), False]


@app.callback(
    Output("job-id", "data"),
    *VIEW_OUTPUTS,
    Output("status-poll", "disabled", allow_duplicate=True),
    Input("upload-trigger", "data"),
    State("model-path", "value"),
    State("sample-rate", "data"),
    State("max-frames", "data"),
    prevent_initial_call=True,
)
def handle_upload(upload_data, model_path, sample_rate, max_frames):
    """Start an analysis once the browser has finished uploading a video."""
    if not upload_data:
        return no_change(len(VIEW_OUTPUTS) + 2)

    upload_file = upload_file_for(upload_data.get("upload_id"))
    filename = upload_data.get("filename") or "video.mp4"

    if upload_file is None or not upload_file.exists():
        return [dash.no_update, *view("error", error="The uploaded file could not be found. Please try again."), True]
    if not is_known_checkpoint(model_path):
        return [dash.no_update, *view("error", error="No model is selected. Add one to dashboard/models/ and refresh this page."), True]

    try:
        job = job_store.create_job_from_path(
            filename=filename,
            existing_path=upload_file,
            model_path=Path(model_path),
            sample_rate=float(sample_rate or DEFAULT_SAMPLE_RATE),
            max_frames=int(max_frames) if max_frames else None,
            preprocess_mode="segmentation",
        )
    except Exception as exc:
        return [dash.no_update, *view("error", error=str(exc)), True]
    return [job.job_id, *view("processing", message=job.message, filename=filename), False]


@app.callback(
    *VIEW_OUTPUTS,
    Output("video-player", "src"),
    Output("inference-data", "data"),
    Output("toolbar-title", "children"),
    Output("toolbar-subtitle", "children"),
    Output("status-poll", "disabled", allow_duplicate=True),
    Input("status-poll", "n_intervals"),
    State("job-id", "data"),
    State("upload-trigger", "data"),
    prevent_initial_call=True,
)
def check_status(_n, job_id, upload_data):
    """Follow the running job on each poll, and send the results to the page when ready."""
    job = job_store.get(job_id) if job_id else None
    if job is None:
        return [*no_change(len(VIEW_OUTPUTS) + 4), True]
    filename = (upload_data or {}).get("filename") or job.video_filename

    if job.status == "ready" and job.result:
        result = job.result
        data = {
            "filename": filename,
            "fps": result.fps,
            "frameStride": result.frame_stride,
            "windowLen": result.window_len,
            "windowStride": result.window_stride,
            "poses": f"/poses/{job.job_id}",
            "wholeVideo": max(result.avg_probs, key=result.avg_probs.get),
            "notices": result.notices,
            "windows": [
                {"start": w.start_time_s, "end": w.end_time_s, "probs": w.probs, "cumulative": w.cumulative_probs}
                for w in result.windows
            ],
        }
        model = job.model_path.parent.name
        return [*view("ready", filename=filename), job.media_url, data, filename, f"Analyzed with {model}", True]

    if job.status == "error":
        return [*view("error", error=job.error or "Unknown error."), *no_change(4), True]

    return [*view("processing", message=job.message, filename=filename), *no_change(4), False]


