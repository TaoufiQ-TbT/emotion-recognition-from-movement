# Upload IDs are generated by the browser; anything else could be used to escape UPLOADS_DIR.
UPLOAD_ID_RE = re.compile(r"[A-Za-z0-9]{8,64}")


def available_checkpoints() -> List[Path]:
    """Return the checkpoint of every model available right now."""
    return list_available_checkpoints(extra_dirs=[MODELS_DIR])


def is_known_checkpoint(model_path: Optional[str]) -> bool:
    """Only checkpoints listed in the sidebar may be loaded, never an arbitrary path."""
    return bool(model_path) and model_path in {str(p) for p in available_checkpoints()}


def upload_file_for(upload_id: Optional[str]) -> Optional[Path]:
    """Path of a chunked upload, or None when the ID is malformed."""
    if not isinstance(upload_id, str) or not UPLOAD_ID_RE.fullmatch(upload_id):
        return None
    return UPLOADS_DIR / "temp" / upload_id / "video.mp4"


