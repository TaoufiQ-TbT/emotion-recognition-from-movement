"""Plot per-frame visibility from the CSV files written by pose_estimation.py."""
from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Iterable, List, Tuple

import matplotlib.pyplot as plt


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot visibility ratios from one or more metrics CSV files."
    )
    parser.add_argument(
        "csv_files",
        nargs="+",
        type=Path,
        help="Paths to CSV files generated by pose_estimation.py (--metrics-csv).",
    )
    parser.add_argument(
        "--labels",
        nargs="*",
        help="Optional series labels. Defaults to the CSV filename stem.",
    )
    parser.add_argument(
        "--column",
        default="world_visible_ratio",
        help="CSV column to plot (default: world_visible_ratio).",
    )
    parser.add_argument(
        "--secondary-column",
        help="Optional second column to overlay (e.g., image_visible_ratio).",
    )
    parser.add_argument(
        "--save",
        type=Path,
        help="Path to save the figure instead of displaying interactively.",
    )
    parser.add_argument(
        "--title",
        default="Visibility Comparison",
        help="Plot title (default: Visibility Comparison).",
    )
    return parser.parse_args()


def load_series(
    csv_path: Path, column: str
) -> Tuple[List[int], List[float]]:
    """Return the frame indices and values of one column. Unreadable cells become NaN."""
    frames: List[int] = []
    values: List[float] = []

    with csv_path.open("r", newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        fieldnames = reader.fieldnames or []
        derived = None

        def require_fields(required: Iterable[str]) -> bool:
            return all(name in fieldnames for name in required)

        # A missing ratio column can be rebuilt from the raw counts.
        if column not in fieldnames:
            if column == "world_visible_ratio" and require_fields(
                ("world_landmarks_visible", "world_landmarks_total")
            ):
                derived = ("world_landmarks_visible", "world_landmarks_total")
            elif column == "image_visible_ratio" and require_fields(
                ("image_landmarks_visible", "image_landmarks_total")
            ):
                derived = ("image_landmarks_visible", "image_landmarks_total")
            else:
                raise SystemExit(
                    f"Column '{column}' not found in {csv_path}. "
                    f"Available columns: {', '.join(fieldnames)}"
                )
        for row in reader:
            try:
                frames.append(int(row["frame_index"]))
            except (TypeError, ValueError):
                continue

            if derived:
                num = row.get(derived[0], "")
                den = row.get(derived[1], "")
                try:
                    num_f = float(num)
                    den_f = float(den)
                    values.append(num_f / den_f if den_f else float("nan"))
                except ValueError:
                    values.append(float("nan"))
            else:
                cell = row.get(column)
                if cell in (None, ""):
                    values.append(float("nan"))
                else:
                    try:
                        values.append(float(cell))
                    except ValueError:
                        values.append(float("nan"))
    return frames, values


def configure_labels(
    csv_files: Iterable[Path], labels: Iterable[str] | None
) -> List[str]:
    """Return one label per CSV file, using the file names by default."""
    labels_list = list(labels or [])
    if labels_list and len(labels_list) != len(list(csv_files)):
        raise SystemExit(
            "Number of labels must match number of CSV files "
            f"({len(labels_list)} provided for {len(list(csv_files))} files)."
        )
    if not labels_list:
        labels_list = [path.stem for path in csv_files]
    return labels_list


def plot_series(
    csv_files: List[Path],
    labels: List[str],
    column: str,
    secondary_column: str | None,
    title: str,
) -> plt.Figure:
    """Draw one line per CSV file, plus a dashed line for the optional second column."""
    fig, ax = plt.subplots(figsize=(8, 4.5))

    for csv_path, label in zip(csv_files, labels):
        frames, values = load_series(csv_path, column)
        ax.plot(frames, values, label=f"{label} – {column}")

        if secondary_column:
            _, sec_values = load_series(csv_path, secondary_column)
            ax.plot(
                frames,
                sec_values,
                linestyle="--",
                alpha=0.7,
                label=f"{label} – {secondary_column}",
            )

    ax.set_xlabel("Frame index")
    ax.set_ylabel(column.replace("_", " ").title())
    ax.set_title(title)
    ax.set_ylim(0.0, 1.05)
    ax.grid(True, linestyle="--", linewidth=0.5, alpha=0.4)
    ax.legend()
    fig.tight_layout()
    return fig


def main() -> None:
    args = parse_args()

    csv_files = [path.expanduser().resolve() for path in args.csv_files]
    for csv_path in csv_files:
        if not csv_path.exists():
            raise SystemExit(f"Metrics CSV not found: {csv_path}")

    labels = configure_labels(csv_files, args.labels)
    figure = plot_series(
        csv_files, labels, args.column, args.secondary_column, args.title
    )

    if args.save:
        args.save.parent.mkdir(parents=True, exist_ok=True)
        figure.savefig(args.save, dpi=200)
        print(f"Saved plot to {args.save}")
    else:
        plt.show()


if __name__ == "__main__":
    main()